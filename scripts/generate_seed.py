import os
import random
from datetime import datetime, timedelta
from faker import Faker

# Set up Faker with Indian locale
fake = Faker('en_IN')

# Seed for reproducibility
random.seed(42)
Faker.seed(42)

def escape(text):
    if text is None:
        return "NULL"
    return f"'{str(text).replace('\'', '\'\'')}'"

def generate_seed():
    out_dir = os.path.join(os.path.dirname(__file__), '..', 'sql')
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, 'seed.sql')

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write("-- ==========================================\n")
        f.write("-- CampusSwap Database Seed File\n")
        f.write("-- Generated by generate_seed.py\n")
        f.write("-- ==========================================\n\n")
        
        f.write("USE campusswap;\n\n")
        f.write("START TRANSACTION;\n\n")
        f.write("SET FOREIGN_KEY_CHECKS = 0;\n\n")

        # TRUNCATE tables (optional, but good for fresh seeds)
        tables = ['REVIEW', 'REQUEST', 'PAYMENT', 'ORDER_ITEM', 'ORDERS', 
                  'BOOK_DETAILS', 'LISTING', 'CATEGORY', 'BUYER', 'SELLER', 'USER']
        for t in tables:
            f.write(f"TRUNCATE TABLE `{t}`;\n")
        f.write("\nSET FOREIGN_KEY_CHECKS = 1;\n\n")

        # 1. GENERATE USERS
        f.write("-- --------------------------------------------------------\n")
        f.write("-- Table: USER\n")
        f.write("-- --------------------------------------------------------\n")
        
        blocks = ['Block-A', 'Block-B', 'Block-C', 'Block-D', 'Block-E', 'Block-F', 'Block-G', 'Block-H', 'Girls-Hostel-1', 'Girls-Hostel-2']
        user_ids = []
        for i in range(1, 101):
            name = fake.name()
            # simple email logic
            email = f"{name.split()[0].lower()}.{name.split()[-1].lower()}{i}@campusswap.in".replace(" ", "")
            phone = f"+91{fake.numerify('##########')}"
            hostel = random.choice(blocks)
            room = random.randint(100, 599)
            joined_at = fake.date_time_between(start_date='-2y', end_date='now').strftime('%Y-%m-%d %H:%M:%S')
            
            f.write(f"INSERT INTO `USER` (user_id, name, email, phone, hostel_block, room_no, joined_at) VALUES ")
            f.write(f"({i}, {escape(name)}, {escape(email)}, {escape(phone)}, {escape(hostel)}, {room}, '{joined_at}');\n")
            user_ids.append(i)
        
        # 2. GENERATE SELLERS
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: SELLER\n")
        f.write("-- --------------------------------------------------------\n")
        seller_ids = random.sample(user_ids, 70)
        for sid in seller_ids:
            upi_id = f"user{sid}@upi"
            total_sales = 0
            avg_rating = round(random.uniform(3.0, 5.0), 1)
            f.write(f"INSERT INTO SELLER (seller_id, upi_id, total_sales, avg_rating) VALUES ({sid}, {escape(upi_id)}, {total_sales}, {avg_rating});\n")

        # 3. GENERATE BUYERS
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: BUYER\n")
        f.write("-- --------------------------------------------------------\n")
        buyer_ids = random.sample(user_ids, 80)
        for bid in buyer_ids:
            wallet_balance = round(random.uniform(0, 2000), 2)
            f.write(f"INSERT INTO BUYER (buyer_id, wallet_balance) VALUES ({bid}, {wallet_balance});\n")

        # 4. GENERATE CATEGORY
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: CATEGORY\n")
        f.write("-- --------------------------------------------------------\n")
        categories = [
            (1, 'Books', None),
            (2, 'Electronics', None),
            (3, 'Stationery', None),
            (4, 'Sports', None),
            (5, 'Clothing', None),
            (6, 'Furniture', None),
            (7, 'Accessories', None),
            (8, 'Engineering Books', 1),
            (9, 'Medical Books', 1),
            (10, 'Fiction', 1),
            (11, 'Calculators', 2),
            (12, 'Earphones', 2),
            (13, 'Cricket', 4),
            (14, 'Badminton', 4),
            (15, 'Lab Equipment', 3)
        ]
        
        for cid, name, parent in categories:
            parent_val = parent if parent is not None else "NULL"
            f.write(f"INSERT INTO CATEGORY (category_id, name, parent_category_id) VALUES ({cid}, {escape(name)}, {parent_val});\n")

        # 5. GENERATE LISTING & BOOK_DETAILS
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: LISTING & BOOK_DETAILS\n")
        f.write("-- --------------------------------------------------------\n")
        listing_ids = []
        book_details_listings = []
        
        conditions = ['NEW', 'LIKE_NEW', 'GOOD', 'FAIR', 'POOR']
        statuses = ['ACTIVE'] * 70 + ['SOLD'] * 20 + ['EXPIRED'] * 5 + ['REMOVED'] * 5
        
        book_titles = [
            'Data Structures by Tanenbaum 3rd Edition',
            'Database System Concepts by Korth',
            'Fundamentals of Database Systems Navathe',
            'Introduction to Algorithms CLRS',
            'Let Us C by Yashavant Kanetkar',
            'Higher Engineering Mathematics B.S. Grewal'
        ]
        
        other_titles = [
            'Casio fx-991EX Scientific Calculator',
            'boAt Rockerz 255 Pro+',
            'Kookaburra Cricket Bat',
            'Yonex GR 303 Badminton Racquet',
            'Drafter for Engineering Drawing',
            'Study Table with chair'
        ]
        
        for i in range(1, 501):
            seller_id = random.choice(seller_ids)
            
            is_book = (i <= 200)
            if is_book:
                category_id = random.choice([1, 8, 9, 10])
                title = random.choice(book_titles) + f" (Copy {i})"
            else:
                category_id = random.choice([2, 3, 4, 5, 6, 7, 11, 12, 13, 14, 15])
                title = random.choice(other_titles) + f" (Item {i})"
                
            desc = fake.text(max_nb_chars=100)
            price = round(random.uniform(50.0, 5000.0), 2)
            quantity = random.randint(1, 5)
            condition = random.choice(conditions)
            status = random.choice(statuses)
            created_at = fake.date_time_between(start_date='-1y', end_date='now').strftime('%Y-%m-%d %H:%M:%S')
            
            f.write(f"INSERT INTO LISTING (listing_id, seller_id, category_id, title, description, price, quantity, `condition`, status, created_at, updated_at) VALUES ")
            f.write(f"({i}, {seller_id}, {category_id}, {escape(title)}, {escape(desc)}, {price}, {quantity}, {escape(condition)}, {escape(status)}, '{created_at}', '{created_at}');\n")
            
            listing_ids.append({'id': i, 'price': price, 'qty': quantity})
            
            if is_book:
                isbn = fake.isbn13()
                author = fake.name()
                edition = f"{random.randint(1, 10)}th"
                subject = fake.word()
                f.write(f"INSERT INTO BOOK_DETAILS (listing_id, isbn, author, edition, subject) VALUES ({i}, {escape(isbn)}, {escape(author)}, {escape(edition)}, {escape(subject)});\n")

        # 6. GENERATE ORDERS, ORDER_ITEM, PAYMENT
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: ORDERS, ORDER_ITEM, PAYMENT\n")
        f.write("-- --------------------------------------------------------\n")
        
        order_statuses = ['PENDING', 'CONFIRMED', 'DELIVERED', 'CANCELLED']
        payment_methods = ['UPI', 'CASH', 'WALLET']
        payment_statuses = ['PENDING', 'COMPLETED', 'FAILED', 'REFUNDED']
        
        item_id_counter = 1
        
        for i in range(1, 301):
            buyer_id = random.choice(buyer_ids)
            order_date = fake.date_time_between(start_date='-6m', end_date='now').strftime('%Y-%m-%d %H:%M:%S')
            status = random.choice(order_statuses)
            
            # Select 1 to 3 items
            num_items = random.randint(1, 3)
            selected_listings = random.sample(listing_ids, num_items)
            
            total_amount = 0
            order_items = []
            
            for listing in selected_listings:
                purchase_qty = random.randint(1, listing['qty'])
                price_at_purchase = listing['price'] # assume current price
                item_total = purchase_qty * price_at_purchase
                total_amount += item_total
                order_items.append((item_id_counter, i, listing['id'], purchase_qty, price_at_purchase))
                item_id_counter += 1
            
            f.write(f"INSERT INTO ORDERS (order_id, buyer_id, order_date, total_amount, status) VALUES ({i}, {buyer_id}, '{order_date}', {total_amount}, {escape(status)});\n")
            
            for oi in order_items:
                f.write(f"INSERT INTO ORDER_ITEM (item_id, order_id, listing_id, quantity, price_at_purchase) VALUES ({oi[0]}, {oi[1]}, {oi[2]}, {oi[3]}, {oi[4]});\n")
                
            payment_method = random.choice(payment_methods)
            payment_status = random.choice(payment_statuses)
            paid_at = "NULL" if payment_status != 'COMPLETED' else f"'{order_date}'"
            f.write(f"INSERT INTO PAYMENT (payment_id, order_id, amount, method, status, paid_at) VALUES ({i}, {i}, {total_amount}, {escape(payment_method)}, {escape(payment_status)}, {paid_at});\n")

        # 7. GENERATE REQUEST
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: REQUEST\n")
        f.write("-- --------------------------------------------------------\n")
        request_statuses = ['OPEN', 'FULFILLED', 'CLOSED']
        req_titles = ['Looking for DBMS by Navathe', 'Need a scientific calculator', 'Looking for lab coat', 'Wanted: EG Drafter']
        for i in range(1, 101):
            uid = random.choice(user_ids)
            cid = random.randint(1, 15)
            title = random.choice(req_titles) + f" {i}"
            desc = fake.text(max_nb_chars=50)
            budget = round(random.uniform(100.0, 1000.0), 2)
            status = random.choice(request_statuses)
            created_at = fake.date_time_between(start_date='-2m', end_date='now').strftime('%Y-%m-%d %H:%M:%S')
            
            f.write(f"INSERT INTO REQUEST (request_id, user_id, category_id, title, description, budget_max, status, created_at) VALUES ")
            f.write(f"({i}, {uid}, {cid}, {escape(title)}, {escape(desc)}, {budget}, {escape(status)}, '{created_at}');\n")

        # 8. GENERATE REVIEW
        f.write("\n-- --------------------------------------------------------\n")
        f.write("-- Table: REVIEW\n")
        f.write("-- --------------------------------------------------------\n")
        review_pairs = set()
        for i in range(1, 201):
            # ensure unique (reviewer_id, listing_id)
            while True:
                reviewer_id = random.choice(user_ids)
                listing_id = random.choice(listing_ids)['id']
                if (reviewer_id, listing_id) not in review_pairs:
                    review_pairs.add((reviewer_id, listing_id))
                    break
            
            rating = random.choices([1, 2, 3, 4, 5], weights=[0.05, 0.05, 0.2, 0.4, 0.3])[0]
            comment = fake.sentence(nb_words=10)
            created_at = fake.date_time_between(start_date='-1m', end_date='now').strftime('%Y-%m-%d %H:%M:%S')
            
            f.write(f"INSERT INTO REVIEW (review_id, reviewer_id, listing_id, rating, comment, created_at) VALUES ")
            f.write(f"({i}, {reviewer_id}, {listing_id}, {rating}, {escape(comment)}, '{created_at}');\n")

        f.write("\nCOMMIT;\n")

    print(f"Seed file generated successfully at {os.path.abspath(out_path)}")

if __name__ == "__main__":
    generate_seed()
